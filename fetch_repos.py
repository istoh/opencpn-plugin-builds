#!/usr/bin/env python3
"""Clone the public Git repositories named in the OpenCPN master catalog."""

import argparse
from collections import defaultdict
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import urlsplit
from urllib.request import urlopen
import xml.etree.ElementTree as ET

MASTER = "https://raw.githubusercontent.com/OpenCPN/plugins/master/ocpn-plugins.xml"
MAX_CATALOG = 16 * 1024 * 1024
FORGES = {"github.com", "gitlab.com", "codeberg.org", "bitbucket.org"}
COMPONENT = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_.-]*\Z")

BUILD_SCRIPT = """#!/usr/bin/env bash
# Generated by fetch.sh. This file can be customized per repository.
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")"

if [[ ! -f CMakeLists.txt ]]; then
    printf 'No root CMakeLists.txt. Adapt this build.sh to the upstream build instructions.\\n' >&2
    exit 1
fi
build_dir=${OPENCPN_BUILD_DIR:-build-native}
cmake -S . -B "$build_dir" -DCMAKE_BUILD_TYPE=Release "$@"
cmake --build "$build_dir" --config Release --parallel "${OPENCPN_BUILD_JOBS:-2}"
if [[ ${OPENCPN_BUILD_TARBALL:-1} == 1 ]]; then
    targets=$(cmake --build "$build_dir" --target help)
    if grep -Eq '(^[.[:space:]]*tarball([[:space:]]|:|$))' <<< "$targets"; then
        cmake --build "$build_dir" --config Release --target tarball
    else
        printf 'No tarball target. Compiled outputs are in %s.\\n' "$build_dir"
    fi
fi
"""


def repository(source):
    url = urlsplit(source)
    host = url.hostname
    if host not in FORGES or url.scheme not in {"http", "https", "git"}:
        return None
    parts = url.path.strip("/").split("/")
    if host == "gitlab.com":
        if "-" in parts:
            parts = parts[:parts.index("-")]
    else:
        parts = parts[:2]
    if len(parts) < 2:
        return None
    parts[-1] = parts[-1].removesuffix(".git")
    if not all(COMPONENT.fullmatch(part) for part in parts):
        return None
    return f"https://{host}/{'/'.join(parts)}.git"


def read_catalog(path):
    stream = path.open("rb") if path else urlopen(MASTER, timeout=30)
    with stream:
        data = stream.read(MAX_CATALOG + 1)
    if len(data) > MAX_CATALOG:
        raise ValueError("catalog exceeds 16 MiB")
    root = ET.fromstring(data)
    if root.tag != "plugins":
        raise ValueError("expected an OpenCPN plugins catalog")
    return root.findall("plugin")


def clone_or_reuse(url, destination):
    env = dict(os.environ, GIT_TERMINAL_PROMPT="0")
    if destination.exists() or destination.is_symlink():
        if destination.is_symlink() or not (destination / ".git").exists():
            raise ValueError("destination already exists and is not a checkout")
        remote = subprocess.check_output(
            ["git", "-C", str(destination), "remote", "get-url", "origin"],
            text=True, env=env,
        ).strip()
        canonical = repository(remote)
        if not canonical or canonical.casefold() != url.casefold():
            raise ValueError(f"existing checkout has a different origin: {remote}")
    else:
        subprocess.run(["git", "clone", "--recurse-submodules", "--", url, str(destination)],
                       check=True, env=env)

    script = destination / "build.sh"
    try:
        with script.open("x", encoding="utf-8") as output:
            output.write(BUILD_SCRIPT)
    except FileExistsError:
        return "existing build.sh kept"
    script.chmod(0o755)
    return "build.sh created"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, help="read local XML instead of the master catalog")
    parser.add_argument("--match", action="append", default=[],
                        help="limit to plugin names containing this text (repeatable)")
    parser.add_argument("--list", action="store_true", help="print the clone plan")
    parser.add_argument("--repo", help="select an exact planned checkout directory")
    parser.add_argument("--matrix", action="store_true", help="emit the GitHub Actions matrix without cloning")
    args = parser.parse_args()

    repos = defaultdict(set)
    canonical_urls = {}
    missing = set()
    known = set()
    try:
        for item in read_catalog(args.catalog):
            name = item.findtext("name", "").strip()
            if not name or args.match and not any(query.casefold() in name.casefold()
                                                  for query in args.match):
                continue
            url = repository(item.findtext("source", "").strip())
            if url:
                repos[url.casefold()].add(name)
                canonical_urls.setdefault(url.casefold(), url)
                known.add(name)
            else:
                missing.add(name)
    except (OSError, ValueError, ET.ParseError) as error:
        parser.exit(1, f"{error}\n")

    for name in sorted(missing - known):
        print(f"No supported public Git source in catalog: {name}", file=sys.stderr)
    if not repos:
        parser.exit(1, "No matching public Git repositories.\n")

    root = Path(__file__).resolve().parent
    short_names = defaultdict(int)
    for url in repos:
        short_names[Path(urlsplit(url).path).stem] += 1
    plan = []
    for key, names in sorted(repos.items()):
        url = canonical_urls[key]
        path = Path(urlsplit(url).path)
        directory = path.stem
        if short_names[directory.casefold()] > 1:
            directory = urlsplit(url).hostname + "--" + "--".join(path.parts[1:-1]) + "--" + directory
        if args.repo is None or directory == args.repo:
            plan.append((directory, url, names))
    if not plan:
        parser.exit(1, "No checkout directory matches --repo.\n")
    if args.matrix:
        print(json.dumps({"include": [{"repo": directory, "url": url} for directory, url, _ in plan]}))
        return 0

    failures = 0
    for directory, url, names in plan:
        print(f"{directory}  {url}  ({', '.join(sorted(names))})", flush=True)
        if args.list:
            continue
        try:
            print(f"  {clone_or_reuse(url, root / directory)}", flush=True)
        except (OSError, ValueError, subprocess.CalledProcessError) as error:
            print(f"  FAILED: {error}", file=sys.stderr)
            failures += 1
    print(f"{len(plan)} repositories, {failures} failed.")
    return int(failures > 0)


if __name__ == "__main__":
    raise SystemExit(main())
